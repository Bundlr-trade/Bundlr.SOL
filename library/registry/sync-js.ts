/* registry.json is the source of truth; registry.js is what the mock reads.
   The resolver passes (wiki, crypto descriptions, links) write JSON only, so
   they call this to regenerate the JS mirror and re-inline the mock — without
   it their work never reaches the page. */
const dir = new URL(".", import.meta.url).pathname;
const reg = JSON.parse(await Bun.file(dir + "registry.json").text());
await Bun.write(dir + "registry.js", "// generated by build-registry.ts — do not edit\nwindow.REGISTRY = " + JSON.stringify(reg) + ";\n");
await Bun.$`bun ${dir}inline.ts`;
